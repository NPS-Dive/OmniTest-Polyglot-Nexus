# ==============================================================================
# File: apps/benchmark-runner/powershell/New-ManagerialReport.ps1
# Purpose: Publication-style QAQC comparison from append-only history files.
#          Writes reports/managerial/run_<timestamp>/summary.md + summary.html
# SOLID: SRP - report assembly only. Does not re-run tests.
# ==============================================================================

[CmdletBinding()]
param(
    [int]$LastN = 200
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'Common.ps1')
. (Join-Path $PSScriptRoot 'ReportWriter.ps1')

function Read-OpnHistoryTail {
    param([string]$CsvPath, [int]$Take)
    if (-not (Test-Path -LiteralPath $CsvPath)) { return @() }
    $rows = Import-Csv -LiteralPath $CsvPath
    if ($rows.Count -gt $Take) {
        return $rows | Select-Object -Last $Take
    }
    return @($rows)
}

$history = Join-Path (Get-OpnRunnerRoot) 'reports\history'
$manual = Read-OpnHistoryTail -CsvPath (Join-Path $history 'manual_results.csv') -Take $LastN
$auto = Read-OpnHistoryTail -CsvPath (Join-Path $history 'automated_results.csv') -Take $LastN
$perf = Read-OpnHistoryTail -CsvPath (Join-Path $history 'performance_results.csv') -Take $LastN
$all = @($manual) + @($auto) + @($perf)

$stamp = [DateTime]::UtcNow.ToString('yyyyMMddTHHmmssZ')
$outDir = Join-Path (Get-OpnRunnerRoot) "reports\managerial\run_$stamp"
New-Item -ItemType Directory -Path $outDir -Force | Out-Null

$langs = @('cpp', 'python', 'java', 'go', 'csharp', 'node')
$rankLines = New-Object System.Collections.Generic.List[string]
foreach ($lang in $langs) {
    $slice = @($all | Where-Object { $_.language -eq $lang })
    if ($slice.Count -eq 0) {
        [void]$rankLines.Add(('| {0} | n/a | n/a | n/a | n/a | n/a | 0 |' -f $lang))
        continue
    }
    $p90 = ($slice | Measure-Object -Property p90_ms -Average).Average
    $p95 = ($slice | Measure-Object -Property p95_ms -Average).Average
    $p98 = ($slice | Measure-Object -Property p98_ms -Average).Average
    $p99 = ($slice | Measure-Object -Property p99_ms -Average).Average
    $ttl = ($slice | Measure-Object -Property ttl_ms -Average).Average
    [void]$rankLines.Add(('| {0} | {1:N1} | {2:N1} | {3:N1} | {4:N1} | {5:N1} | {6} |' -f $lang, $p90, $p95, $p98, $p99, $ttl, $slice.Count))
}

$passCount = @($all | Where-Object { $_.pass -eq 'True' -or $_.pass -eq $true }).Count
$failCount = $all.Count - $passCount

$failLines = New-Object System.Collections.Generic.List[string]
$failed = @($all | Where-Object { -not ($_.pass -eq 'True' -or $_.pass -eq $true) } | Select-Object -Last 40)
foreach ($row in $failed) {
    $err = [string]$row.error_message
    $err = $err.Replace('|', '/')
    [void]$failLines.Add(('| {0} | {1} | {2} | {3} |' -f $row.timestamp_utc, $row.test_name, $row.language, $err))
}

$rankBlock = [string]::Join([Environment]::NewLine, $rankLines)
$failBlock = [string]::Join([Environment]::NewLine, $failLines)
$manualCount = $manual.Count
$autoCount = $auto.Count
$perfCount = $perf.Count
$allCount = $all.Count

$md = @"
# QAQC managerial report - $stamp

Generated by New-ManagerialReport.ps1. History is append-only; this folder is a snapshot.

## Scope

| Bucket | Rows used (last $LastN per file) |
|--------|----------------------------------|
| Manual | $manualCount |
| Automated | $autoCount |
| Performance / security | $perfCount |

BDD refs: docs/gherkin/*.feature including person-performance.feature.

## Totals

- Rows in this snapshot: **$allCount**
- Passed: **$passCount**
- Failed / skipped: **$failCount**

## Cross-language comparison (mean of available rows)

| Language | mean p90 (ms) | mean p95 (ms) | mean p98 (ms) | mean p99 (ms) | mean TTL (ms) | n |
|----------|---------------|---------------|---------------|---------------|---------------|---|
$rankBlock

Empty cells mean that language has no history yet.

## Failures (this snapshot)

| timestamp_utc | test_name | language | error_message |
|---------------|-----------|----------|---------------|
$failBlock

## Bugs

On new failures, copy reports/bugs/TEMPLATE.md to BUG-<id>.md (ISTQB fields).

## How to refresh

``````powershell
cd apps\benchmark-runner\powershell
.\Invoke-AllManualTests.ps1
.\New-ManagerialReport.ps1
``````
"@

Set-Content -LiteralPath (Join-Path $outDir 'summary.md') -Value $md -Encoding utf8

$html = @"
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8"/>
  <title>QAQC $stamp</title>
  <style>
    body { font-family: Segoe UI, sans-serif; margin: 2rem; color: #1a1a1a; }
    table { border-collapse: collapse; }
    td, th { border: 1px solid #ccc; padding: 0.4rem 0.6rem; }
    th { background: #f4f4f4; }
  </style>
</head>
<body>
  <h1>QAQC managerial report - $stamp</h1>
  <p>Passed $passCount / $allCount. Open summary.md for the full comparison table.</p>
  <p>Grafana: <a href="http://localhost:3000">http://localhost:3000</a></p>
</body>
</html>
"@
Set-Content -LiteralPath (Join-Path $outDir 'summary.html') -Value $html -Encoding utf8

Write-Host "Wrote $outDir"
return $outDir
